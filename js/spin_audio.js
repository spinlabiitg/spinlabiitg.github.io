/* SPIN Lab home page: the S -> P -> IN signal animation and the "Say hey" listener.
   Data: window.SPIN_SIGNAL (js/spin_signal_data.js, generated by scripts/make_signal_data.py).
   Colours come from CSS custom properties (--sig-*), so light/dark mode just works. */
(function () {
  'use strict';
  var D = window.SPIN_SIGNAL;
  if (!D) return;
  var reduceMotion = window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches;
  var root = document.documentElement;

  // ---------- shared helpers ----------
  function clamp(v, a, b) { return v < a ? a : v > b ? b : v; }
  function ease(p) { return p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2; }
  function seg(t, a, b) { return clamp((t - a) / (b - a), 0, 1); }
  function css(name) { return getComputedStyle(root).getPropertyValue(name).trim(); }
  function hex(c) {
    c = c.replace('#', '');
    if (c.length === 3) c = c.replace(/(.)/g, '$1$1');
    return [parseInt(c.slice(0, 2), 16), parseInt(c.slice(2, 4), 16), parseInt(c.slice(4, 6), 16)];
  }
  function rgba(c, a) { var h = hex(c); return 'rgba(' + h[0] + ',' + h[1] + ',' + h[2] + ',' + a + ')'; }
  function lang() { return root.getAttribute('data-lang') === 'hi' ? 'hi' : 'en'; }

  var theme = null; // cached colours + colour map, rebuilt when the theme changes
  function getTheme() {
    var key = css('--sig-bg') + css('--sig-c3');
    if (theme && theme.key === key) return theme;
    var stops = [css('--sig-c0'), css('--sig-c1'), css('--sig-c2'), css('--sig-c3')].map(hex);
    var lut = new Uint8ClampedArray(256 * 3);
    for (var i = 0; i < 256; i++) {
      var p = i / 255 * 3, k = Math.min(2, Math.floor(p)), f = p - k;
      for (var c = 0; c < 3; c++) lut[i * 3 + c] = stops[k][c] + (stops[k + 1][c] - stops[k][c]) * f;
    }
    theme = {
      key: key, lut: lut, bg: css('--sig-bg'), fg: css('--sig-fg'), accent: css('--sig-accent'),
      muted: css('--sig-muted'), grid: css('--sig-grid'),
      k: [css('--sig-k0'), css('--sig-k1'), css('--sig-k2'), css('--sig-k3')]
    };
    theme.specImg = null;
    return theme;
  }
  function lutColor(v01) { var i = Math.round(clamp(v01, 0, 1) * 255) * 3, l = theme.lut; return [l[i], l[i + 1], l[i + 2]]; }

  // Spectrogram of the clip as an offscreen image (nFrames x nMel), built per theme.
  function specImage() {
    var th = getTheme();
    if (th.specImg) return th.specImg;
    var c = document.createElement('canvas'); c.width = D.nFrames; c.height = D.nMel;
    var g = c.getContext('2d'), img = g.createImageData(D.nFrames, D.nMel);
    for (var f = 0; f < D.nFrames; f++) for (var m = 0; m < D.nMel; m++) {
      var col = lutColor(D.spec[f * D.nMel + m] / 99), o = ((D.nMel - 1 - m) * D.nFrames + f) * 4;
      img.data[o] = col[0]; img.data[o + 1] = col[1]; img.data[o + 2] = col[2]; img.data[o + 3] = 255;
    }
    g.putImageData(img, 0, 0);
    th.specImg = c;
    return c;
  }

  // Per-frame spectral centroid (in mel bins), used as the start height of each map point.
  var centroid = [];
  for (var f = 0; f < D.nFrames; f++) {
    var s = 0, w = 0;
    for (var m = 0; m < D.nMel; m++) { var v = D.spec[f * D.nMel + m] / 99; v = v * v; s += v * m; w += v; }
    centroid.push(w ? s / w : D.nMel / 2);
  }

  // Map PCA coordinates into a pixel box with ONE scale for both axes, centred on the data.
  var bbox = (function () {
    var x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9;
    D.map.forEach(function (p) { x0 = Math.min(x0, p[1]); x1 = Math.max(x1, p[1]); y0 = Math.min(y0, p[2]); y1 = Math.max(y1, p[2]); });
    return { cx: (x0 + x1) / 2, cy: (y0 + y1) / 2, w: x1 - x0 || 1, h: y1 - y0 || 1 };
  })();
  function mapper(L, R, top, bot) {
    var s = Math.min((R - L) * 0.86 / bbox.w, (bot - top) * 0.80 / bbox.h);
    var cx = (L + R) / 2, cy = (top + bot) / 2;
    return function (x, y) { return [cx + (x - bbox.cx) * s, cy - (y - bbox.cy) * s]; };
  }

  function fitCanvas(cv) {
    var r = cv.getBoundingClientRect(), dpr = Math.min(window.devicePixelRatio || 1, 2);
    var w = Math.round(r.width * dpr), h = Math.round(r.height * dpr);
    if (cv.width !== w || cv.height !== h) { cv.width = w; cv.height = h; }
    return dpr;
  }

  // ---------- 1. hero animation ----------
  var T = { S1: 2400, P0: 3000, P1: 5000, P2: 5200, P3: 7000, I0: 7800, I1: 10200, TX0: 9600, TX1: 10400, END: 13600, FADE: 700 };
  var STAGE_START = { S: 0, P: T.P0, IN: T.I0 };
  var STAGE_STILL = { S: T.S1 + 200, P: T.P3 + 400, IN: T.END - T.FADE - 50 };

  function initHero(box) {
    var cv = box.querySelector('canvas'), g = cv.getContext('2d');
    var chips = box.querySelectorAll('[data-stage]');
    var audioEl = new Audio(box.getAttribute('data-audio'));
    var t = 0, last = null, running = false, visible = true, audioOn = false;

    function stageOf(tt) { return tt < T.P0 ? 'S' : tt < T.I0 ? 'P' : 'IN'; }

    function draw(tt) {
      var th = getTheme(), dpr = fitCanvas(cv), W = cv.width, H = cv.height;
      var padX = 18 * dpr, padT = 40 * dpr, padB = 18 * dpr;
      var L = padX, R = W - padX, top = padT, bot = H - padB, mid = (top + bot) / 2, amp = (bot - top) / 2 * 0.92;
      g.clearRect(0, 0, W, H);
      var fadeAll = 1 - seg(tt, T.END - T.FADE, T.END);
      g.globalAlpha = fadeAll;

      // baseline
      g.strokeStyle = th.grid; g.lineWidth = 1 * dpr;
      g.beginPath(); g.moveTo(L, mid); g.lineTo(R, mid); g.stroke();

      // S: waveform draws in (in real time when the audio is playing)
      var waveA = 1 - 0.8 * seg(tt, T.P0, T.P1) - 0.2 * seg(tt, T.P2, T.P3);
      var prog = audioOn ? clamp(audioEl.currentTime / D.dur, 0, 1) : ease(seg(tt, 0, T.S1));
      if (waveA > 0.01) {
        var n = D.wave.length, upto = Math.floor(prog * n), bw = (R - L) / n;
        g.strokeStyle = rgba(th.fg, waveA); g.lineWidth = Math.max(1, bw * 0.8);
        g.beginPath();
        for (var i = 0; i < upto; i++) {
          var x = L + (i + 0.5) * bw;
          g.moveTo(x, mid - D.wave[i][1] * amp); g.lineTo(x, mid - D.wave[i][0] * amp + 0.5);
        }
        g.stroke();
        if (prog < 1 && tt < T.S1 + 300) { // pen tip
          g.fillStyle = th.accent;
          g.beginPath(); g.arc(L + prog * (R - L), mid, 3.5 * dpr, 0, 6.3); g.fill();
        }
      }

      // P (a): extrema samples sweep in, joined by a line
      var dotsA = seg(tt, T.P0, T.P0 + 400) * (1 - seg(tt, T.P3, T.I0));
      if (dotsA > 0.01) {
        var q = ease(seg(tt, T.P0, T.P1)), E = D.extrema;
        g.strokeStyle = rgba(th.accent, 0.45 * dotsA); g.lineWidth = 1.2 * dpr;
        g.beginPath();
        for (var j = 0; j < E.length && E[j][0] <= q; j++) {
          var ex = L + E[j][0] * (R - L), ey = mid - E[j][1] * amp;
          if (j) g.lineTo(ex, ey); else g.moveTo(ex, ey);
        }
        g.stroke();
        g.fillStyle = rgba(th.accent, dotsA);
        for (j = 0; j < E.length && E[j][0] <= q; j++) {
          g.beginPath(); g.arc(L + E[j][0] * (R - L), mid - E[j][1] * amp, 2.1 * dpr, 0, 6.3); g.fill();
        }
      }

      // P (b): spectrogram reveals left to right
      var specA = seg(tt, T.P2, T.P2 + 300) * (1 - 0.9 * seg(tt, T.I0, T.I0 + 900));
      if (specA > 0.01) {
        var r = ease(seg(tt, T.P2, T.P3)), sw = Math.max(1, Math.round(D.nFrames * r));
        g.globalAlpha = fadeAll * specA;
        g.imageSmoothingEnabled = true;
        g.drawImage(specImage(), 0, 0, sw, D.nMel, L, top, (R - L) * sw / D.nFrames, bot - top);
        g.globalAlpha = fadeAll;
      }

      // IN: frames fly to a 2-D map of sounds (PCA of their spectra, one scale for both axes),
      // coloured by the word they came from; each word is then traced as a path in time order.
      if (tt >= T.I0) {
        var mapToPx = mapper(L, R, top + 10 * dpr, bot);
        var pos = [];
        for (var k = 0; k < D.map.length; k++) {
          var p = D.map[k], fr = p[0];
          var delay = (fr / D.nFrames) * 900, mp = ease(seg(tt, T.I0 + delay, T.I0 + delay + 1300));
          var x0 = L + (fr + 0.5) / D.nFrames * (R - L), y0 = bot - centroid[fr] / D.nMel * (bot - top);
          var xy1 = mapToPx(p[1], p[2]);
          pos.push([x0 + (xy1[0] - x0) * mp, y0 + (xy1[1] - y0) * mp]);
        }
        var pathA = ease(seg(tt, T.I1 - 400, T.TX0 + 200));
        if (pathA > 0) { // word paths: join consecutive frames of the same word
          g.lineWidth = 1.4 * dpr;
          for (k = 1; k < D.map.length; k++) {
            var a = D.map[k - 1], b = D.map[k];
            if (a[3] !== b[3] || b[0] - a[0] > 2) continue;
            g.strokeStyle = rgba(th.k[b[3]], 0.55 * pathA);
            g.beginPath(); g.moveTo(pos[k - 1][0], pos[k - 1][1]); g.lineTo(pos[k][0], pos[k][1]); g.stroke();
          }
        }
        for (k = 0; k < D.map.length; k++) {
          var q = D.map[k], dmp = ease(seg(tt, T.I0 + (q[0] / D.nFrames) * 900, T.I0 + (q[0] / D.nFrames) * 900 + 1300));
          var cs = lutColor(0.75), ck = hex(th.k[q[3]]);
          g.fillStyle = 'rgb(' + Math.round(cs[0] + (ck[0] - cs[0]) * dmp) + ',' + Math.round(cs[1] + (ck[1] - cs[1]) * dmp) + ',' + Math.round(cs[2] + (ck[2] - cs[2]) * dmp) + ')';
          g.beginPath(); g.arc(pos[k][0], pos[k][1], (2 + 1.8 * dmp) * dpr, 0, 6.3); g.fill();
        }
        var txA = ease(seg(tt, T.TX0, T.TX1));
        if (txA > 0) {
          // the sentence, each word in its colour (doubles as the legend)
          g.font = '600 ' + Math.round(17 * dpr) + 'px "Source Sans Pro", sans-serif';
          g.textAlign = 'left';
          var parts = [['“', th.fg]], total = 0;
          D.words.forEach(function (w, i) { parts.push([(i ? ' ' : '') + w.w, th.k[i]]); });
          parts.push(['”', th.fg]);
          parts.forEach(function (pt) { total += g.measureText(pt[0]).width; });
          var tx = (W - total) / 2;
          parts.forEach(function (pt) { g.fillStyle = rgba(pt[1], txA); g.fillText(pt[0], tx, 26 * dpr); tx += g.measureText(pt[0]).width; });
          (D.notes || []).forEach(function (n) {
            var np = mapToPx(n.x, n.y);
            g.fillStyle = rgba(th.k[n.word], txA);
            g.font = 'italic 600 ' + Math.round(12 * dpr) + 'px "Source Sans Pro", sans-serif';
            g.textAlign = 'center';
            g.fillText(n.text, np[0], np[1] - 10 * dpr);
          });
        }
      }

      // corner label
      g.globalAlpha = fadeAll * (1 - seg(tt, T.TX0 - 400, T.TX0)); // make room for the words
      g.fillStyle = th.muted; g.font = Math.round(11 * dpr) + 'px "Source Sans Pro", sans-serif'; g.textAlign = 'left';
      var lab = { S: 'amplitude · time', P: tt < T.P2 ? 'samples at extrema' : 'frequency · time', IN: 'a map of sounds' }[stageOf(tt)];
      g.fillText(lab, L, 18 * dpr);
      g.globalAlpha = 1;

      var st = stageOf(tt);
      for (var c = 0; c < chips.length; c++) chips[c].classList.toggle('on', chips[c].getAttribute('data-stage') === st);
      box.setAttribute('data-current', st);
    }

    function frame(now) {
      if (!running) return;
      if (last === null) last = now;
      var dt = Math.min(now - last, 100); last = now;
      if (audioOn && t < T.S1) t = audioEl.currentTime / D.dur * T.S1; else t += dt;
      if (reduceMotion && t >= STAGE_STILL.IN) { t = STAGE_STILL.IN; draw(t); running = false; return; }
      if (t >= T.END) t = 0;
      draw(t);
      requestAnimationFrame(frame);
    }
    function start() { if (reduceMotion || running || !visible || document.hidden) return; running = true; last = null; requestAnimationFrame(frame); }
    function stop() { running = false; }

    audioEl.addEventListener('ended', function () { audioOn = false; if (t < T.S1) t = T.S1; });
    box.querySelector('.js-hear').addEventListener('click', function () {
      t = 0; audioEl.currentTime = 0;
      audioEl.play().then(function () { audioOn = true; }).catch(function () { audioOn = false; });
      if (reduceMotion) { reduceMotion = false; start(); reduceMotion = true; } // play once even with reduced motion
    });
    [].forEach.call(chips, function (ch) {
      ch.addEventListener('click', function () {
        var s = ch.getAttribute('data-stage');
        audioOn = false; audioEl.pause();
        t = reduceMotion ? STAGE_STILL[s] : STAGE_START[s];
        draw(t);
      });
    });

    if ('IntersectionObserver' in window) {
      new IntersectionObserver(function (es) { visible = es[0].isIntersecting; visible ? start() : stop(); }).observe(cv);
    }
    document.addEventListener('visibilitychange', function () { document.hidden ? stop() : start(); });
    window.addEventListener('resize', function () { draw(t); });
    // redraw on theme toggle even when paused
    new MutationObserver(function () { draw(t); }).observe(root, { attributes: true, attributeFilter: ['data-theme', 'data-lang'] });

    box.spinSeek = function (ms) { stop(); t = ms; draw(t); }; // for testing/screenshots: el.spinSeek(8000)
    if (reduceMotion) { t = STAGE_STILL.P; draw(t); } else start();
  }

  // ---------- 2. "Say hey": live microphone or our recorded hello ----------
  var MSG = {
    idle: { en: 'Our hello, as a spectrogram. Now try yours.', hi: 'हमारा अभिवादन, स्पेक्ट्रोग्राम के रूप में। अब आप बोलकर देखें।' },
    listen: { en: 'Listening… say hello!', hi: 'सुन रहे हैं… नमस्ते कहिए!' },
    play: { en: 'Playing “Welcome to SPIN Lab”…', hi: '“Welcome to SPIN Lab” चल रहा है…' },
    nomic: { en: 'Microphone not available. Try playing our hello instead.', hi: 'माइक्रोफ़ोन उपलब्ध नहीं है। इसके बजाय हमारा अभिवादन सुनें।' },
    done: { en: 'That was you! Want to work with signals like these? Say hey by email.', hi: 'यह आपकी आवाज़ थी! ऐसे संकेतों पर काम करना चाहेंगे? ईमेल से संपर्क करें।' }
  };

  function initHey(box) {
    var cv = box.querySelector('canvas'), g = cv.getContext('2d');
    var status = box.querySelector('.hey-status'), micBtn = box.querySelector('.js-mic'), playBtn = box.querySelector('.js-play');
    var ctx = null, analyser = null, stream = null, srcNode = null, raf = null, timer = null, mode = 'idle', statusKey = 'idle';
    var specCanvas = document.createElement('canvas'), sg = specCanvas.getContext('2d');

    function say(k) { statusKey = k; status.textContent = MSG[k][lang()]; }

    function drawIdle() {
      var th = getTheme(), dpr = fitCanvas(cv), W = cv.width, H = cv.height, half = H * 0.42;
      g.clearRect(0, 0, W, H);
      g.fillStyle = th.bg; g.fillRect(0, 0, W, H);
      // waveform on top
      var n = D.wave.length, bw = W / n;
      g.strokeStyle = th.fg; g.lineWidth = Math.max(1, bw * 0.8); g.beginPath();
      for (var i = 0; i < n; i++) { var x = (i + 0.5) * bw; g.moveTo(x, half / 2 - D.wave[i][1] * half * 0.45); g.lineTo(x, half / 2 - D.wave[i][0] * half * 0.45 + 0.5); }
      g.stroke();
      g.drawImage(specImage(), 0, 0, D.nFrames, D.nMel, 0, half, W, H - half);
    }

    function setupSpec() {
      var dpr = fitCanvas(cv);
      specCanvas.width = cv.width; specCanvas.height = Math.round(cv.height * 0.58);
      sg.fillStyle = getTheme().bg; sg.fillRect(0, 0, specCanvas.width, specCanvas.height);
      return dpr;
    }

    function loop() {
      var th = getTheme(), W = cv.width, H = cv.height, half = H - specCanvas.height;
      var td = new Uint8Array(analyser.fftSize), fd = new Uint8Array(analyser.frequencyBinCount);
      analyser.getByteTimeDomainData(td); analyser.getByteFrequencyData(fd);
      // scroll spectrogram 2px left and add a new column (0-8 kHz)
      var step = Math.max(2, Math.round(W / 300));
      sg.drawImage(specCanvas, -step, 0);
      var h = specCanvas.height, nyq = ctx.sampleRate / 2, maxBin = Math.floor(fd.length * Math.min(1, 8000 / nyq));
      for (var y = 0; y < h; y++) {
        var b = Math.floor(Math.pow(1 - y / h, 1.6) * (maxBin - 1)) + 1, c = lutColor(fd[b] / 255);
        sg.fillStyle = 'rgb(' + c[0] + ',' + c[1] + ',' + c[2] + ')'; sg.fillRect(W - step, y, step, 1);
      }
      g.fillStyle = th.bg; g.fillRect(0, 0, W, half);
      g.strokeStyle = th.accent; g.lineWidth = 1.5 * (window.devicePixelRatio || 1); g.beginPath();
      for (var i = 0; i < td.length; i++) {
        var x = i / (td.length - 1) * W, yy = half / 2 + (td[i] - 128) / 128 * half * 0.9;
        if (i) g.lineTo(x, yy); else g.moveTo(x, yy);
      }
      g.stroke();
      g.drawImage(specCanvas, 0, half);
      raf = requestAnimationFrame(loop);
    }

    function ensureCtx() {
      if (!ctx) { var AC = window.AudioContext || window.webkitAudioContext; ctx = new AC(); }
      if (ctx.state === 'suspended') ctx.resume();
      analyser = ctx.createAnalyser(); analyser.fftSize = 1024; analyser.smoothingTimeConstant = 0.2;
    }

    function stopAll(nextKey) {
      cancelAnimationFrame(raf); clearTimeout(timer);
      if (stream) { stream.getTracks().forEach(function (tr) { tr.stop(); }); stream = null; }
      if (srcNode) { try { srcNode.stop && srcNode.stop(); } catch (e) {} try { srcNode.disconnect(); } catch (e) {} srcNode = null; }
      var wasMic = mode === 'mic';
      mode = 'idle'; box.classList.remove('is-live');
      micBtn.setAttribute('aria-pressed', 'false');
      say(nextKey || (wasMic ? 'done' : 'idle'));
    }

    micBtn.addEventListener('click', function () {
      if (mode === 'mic') { stopAll(); return; }
      stopAll('idle');
      if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) { say('nomic'); return; }
      navigator.mediaDevices.getUserMedia({ audio: { echoCancellation: true, noiseSuppression: false } }).then(function (s) {
        ensureCtx(); stream = s; srcNode = ctx.createMediaStreamSource(s);
        srcNode.connect(analyser); // not connected to the speakers: no echo, nothing stored
        mode = 'mic'; box.classList.add('is-live'); micBtn.setAttribute('aria-pressed', 'true'); say('listen');
        setupSpec(); loop();
        timer = setTimeout(function () { stopAll(); }, 15000);
      }).catch(function () { say('nomic'); });
    });

    playBtn.addEventListener('click', function () {
      stopAll('idle');
      ensureCtx();
      fetch(box.getAttribute('data-audio')).then(function (r) { return r.arrayBuffer(); })
        .then(function (buf) { return new Promise(function (ok, no) { ctx.decodeAudioData(buf, ok, no); }); })
        .then(function (ab) {
          srcNode = ctx.createBufferSource(); srcNode.buffer = ab;
          srcNode.connect(analyser); analyser.connect(ctx.destination);
          srcNode.onended = function () { setTimeout(function () { if (mode === 'play') stopAll('idle'); }, 600); };
          mode = 'play'; box.classList.add('is-live'); say('play');
          setupSpec(); srcNode.start(); loop();
        }).catch(function () { say('idle'); });
    });

    new MutationObserver(function () { say(statusKey); if (mode === 'idle') drawIdle(); })
      .observe(root, { attributes: true, attributeFilter: ['data-theme', 'data-lang'] });
    window.addEventListener('resize', function () { if (mode === 'idle') drawIdle(); });
    say('idle'); drawIdle();
  }

  function boot() {
    var hero = document.querySelector('.signal-hero');
    if (hero) initHero(hero);
    var hey = document.querySelector('.say-hey');
    if (hey) initHey(hey);
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot); else boot();
})();
