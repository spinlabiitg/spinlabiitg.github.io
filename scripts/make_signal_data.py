"""Precompute the data behind the home-page signal animation and the "Say hey" widget.

Input : audio/welcome_to_spinlab.wav  (real recording, mono)
Output: audio/welcome_web.wav          (trimmed, 16-bit, for playback on the site)
        js/spin_signal_data.js         (window.SPIN_SIGNAL = {...})

Run from the site root:  python scripts/make_signal_data.py
"""
import json
import numpy as np
import scipy.io.wavfile as wf
from scipy.signal import butter, sosfiltfilt, argrelextrema

SRC = "audio/welcome_to_spinlab.wav"
T0, T1 = 0.20, 1.55          # keep a little silence around the speech (0.30-1.40 s)
N_WAVE = 480                 # waveform bins (min/max per bin)
N_MEL = 48
TEXT = "Welcome to SPIN Lab"

# Word boundaries in the ORIGINAL recording (seconds). Found by CTC forced alignment of the
# speaker's phonemes (v o l k ʌ m | t uː | s p i n | l aː b) with wav2vec2-lv-60-espeak-cv-ft,
# placing each edge in the gap between neighbouring phone spikes; the to|SPIN edge is the /s/
# onset (high-frequency energy). Re-check these if the recording changes.
WORDS = [("Welcome", 0.30, 0.72), ("to", 0.72, 0.95), ("SPIN", 0.95, 1.23), ("Lab", 1.23, 1.42)]

sr, x = wf.read(SRC)
x = x.astype(np.float64)
if x.ndim > 1:
    x = x.mean(axis=1)
x = x[int(T0 * sr):int(T1 * sr)]
x /= np.abs(x).max()

# Short fades so playback does not click, then save a small 16-bit copy for the web.
fade = int(0.03 * sr)
ramp = np.linspace(0, 1, fade)
x[:fade] *= ramp
x[-fade:] *= ramp[::-1]
wf.write("audio/welcome_web.wav", sr, (x * 0.9 * 32767).astype(np.int16))
dur = len(x) / sr

# 1. Sensing: waveform as min/max per bin.
bins = np.array_split(x, N_WAVE)
wave = [[round(float(b.min()), 3), round(float(b.max()), 3)] for b in bins]

# 2a. Perception: extrema of a low-passed copy (the signal "sampled where it turns").
sos = butter(4, 350, btype="low", fs=sr, output="sos")
y = sosfiltfilt(sos, x)
y /= np.abs(y).max()
idx = np.sort(np.concatenate([argrelextrema(y, np.greater)[0], argrelextrema(y, np.less)[0]]))
idx = idx[np.abs(y[idx]) > 0.08]
extrema = [[round(i / len(x), 4), round(float(y[i]), 3)] for i in idx]

# 2b. Perception: log-mel spectrogram (25 ms window, 10 ms hop).
win, hop = int(0.025 * sr), int(0.010 * sr)
nfft = 512
frames = np.lib.stride_tricks.sliding_window_view(x, win)[::hop] * np.hanning(win)
mag = np.abs(np.fft.rfft(frames, nfft)) ** 2


def hz2mel(f):
    return 2595 * np.log10(1 + f / 700)


def mel2hz(m):
    return 700 * (10 ** (m / 2595) - 1)


edges = mel2hz(np.linspace(hz2mel(80), hz2mel(7600), N_MEL + 2))
fft_f = np.linspace(0, sr / 2, nfft // 2 + 1)
fb = np.zeros((N_MEL, len(fft_f)))
for m in range(N_MEL):
    lo, c, hi = edges[m:m + 3]
    fb[m] = np.clip(np.minimum((fft_f - lo) / (c - lo), (hi - fft_f) / (hi - c)), 0, None)
mel_db = 10 * np.log10(mag @ fb.T + 1e-10)
mel_db = np.clip(mel_db - mel_db.max(), -60, 0)
spec01 = (mel_db + 60) / 60                      # frames x mel, 0..1
spec = (spec01 * 99).round().astype(int)

# 3. Intelligence: each speech frame placed on a 2-D map (PCA of its log-mel spectrum),
#    coloured by the word it belongs to. Both axes share one scale, so distances are honest.
centre_t = (np.arange(spec.shape[0]) * hop + win / 2) / sr + T0      # frame centre, original time
word_of = np.full(spec.shape[0], -1)
for wi, (_, a, b) in enumerate(WORDS):
    word_of[(centre_t >= a) & (centre_t < b)] = wi
energy = spec01.mean(axis=1)
active = np.where((energy > np.percentile(energy, 35)) & (word_of >= 0))[0]
feats = mel_db[active] - mel_db[active].mean(axis=0)
u, s, vt = np.linalg.svd(feats, full_matrices=False)
xy = feats @ vt[:2].T
xy = xy / np.abs(xy).max()
pts = [[int(f), round(float(a), 3), round(float(b), 3), int(word_of[f])] for f, (a, b) in zip(active, xy)]
words = [{"w": w, "t0": round(a - T0, 3), "t1": round(b - T0, 3)} for w, a, b in WORDS]
# Label the /s/ of SPIN (0.95-1.04 s): its hiss forms its own island on the map.
hiss = [k for k, f in enumerate(active) if 0.95 <= centre_t[f] < 1.04]
notes = [{"text": "/s/ in SPIN", "word": 2, "x": round(float(xy[hiss, 0].mean()), 3), "y": round(float(xy[hiss, 1].max()), 3)}] if hiss else []

data = {
    "text": TEXT, "sr": sr, "dur": round(dur, 3), "speech": [round(0.30 - T0, 3), round(1.40 - T0, 3)],
    "wave": wave, "extrema": extrema,
    "nMel": N_MEL, "nFrames": int(spec.shape[0]), "spec": spec.flatten().tolist(),
    "map": pts, "words": words, "notes": notes,
}
with open("js/spin_signal_data.js", "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/make_signal_data.py from audio/welcome_to_spinlab.wav. Do not edit.\n")
    f.write("window.SPIN_SIGNAL = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"dur {dur:.2f}s  extrema {len(extrema)}  frames {spec.shape[0]}  map points {len(pts)}")
